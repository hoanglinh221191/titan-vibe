#!/usr/bin/env python3
"""G1: compare monolithic and regenerated-TPR GROMACS pull trajectories.

Run this script inside Linux/WSL where GROMACS is available.  It uses a
two-particle deterministic NVE fixture and demands byte-identical pull output,
TRR, XTC, EDR, and final GRO after a 100+100 step segmented continuation versus
one 200-step run.  The segment handoff is generated by the production
``titan_path_handoff`` module.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import subprocess
import sys
from typing import Sequence


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from titan_path_handoff import (  # noqa: E402
    compute_force_continuous_handoff,
    mdp_updates_for_handoff,
    patch_mdp_text,
)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def run(command: Sequence[str], *, cwd: Path, log: Path) -> str:
    completed = subprocess.run(
        list(command),
        cwd=cwd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    log.write_text(completed.stdout, encoding="utf-8", newline="\n")
    if completed.returncode != 0:
        raise RuntimeError(
            f"command failed with {completed.returncode}: {' '.join(command)}; "
            f"see {log}"
        )
    return completed.stdout


def xvg_rows(path: Path) -> list[str]:
    return [
        line.strip()
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines()
        if line.strip() and not line.lstrip().startswith(("#", "@"))
    ]


def prepare_output(path: Path) -> None:
    if path.exists() and any(path.iterdir()):
        raise RuntimeError(f"output directory is not empty: {path}")
    path.mkdir(parents=True, exist_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gmx", default="gmx")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    fixture = ROOT / "test" / "titan_path_gromacs_g1_fixture"
    output = args.output.resolve()
    prepare_output(output)
    segmented = output / "segmented"
    monolithic = output / "monolithic"
    segmented.mkdir()
    monolithic.mkdir()

    gmx_version = run(
        [args.gmx, "--version"], cwd=output, log=output / "gmx_version.txt"
    )
    common_grompp = [
        "-c",
        str(fixture / "system.gro"),
        "-p",
        str(fixture / "topol.top"),
        "-n",
        str(fixture / "index.ndx"),
        "-maxwarn",
        "0",
    ]
    run(
        [
            args.gmx,
            "grompp",
            "-f",
            str(fixture / "segment1.mdp"),
            *common_grompp,
            "-o",
            "segment1.tpr",
            "-po",
            "mdout_segment1.mdp",
        ],
        cwd=segmented,
        log=segmented / "grompp_segment1.txt",
    )
    run(
        [
            args.gmx,
            "mdrun",
            "-s",
            "segment1.tpr",
            "-deffnm",
            "run",
            "-px",
            "pullx.xvg",
            "-pf",
            "pullf.xvg",
            "-cpo",
            "run.cpt",
            "-reprod",
            "-ntmpi",
            "1",
            "-ntomp",
            "1",
        ],
        cwd=segmented,
        log=segmented / "mdrun_segment1.txt",
    )

    boundary_fields = xvg_rows(segmented / "pullx.xvg")[-1].split()
    if len(boundary_fields) != 12:
        raise RuntimeError(
            "G1 fixture expected pullx columns: time, coordinate, reference, "
            "three components, reference COM xyz, ligand COM xyz"
        )
    time_ps = float(boundary_fields[0])
    old_coordinate_nm = float(boundary_fields[1])
    old_reference_nm = float(boundary_fields[2])
    reference_com_nm = tuple(float(value) for value in boundary_fields[6:9])
    ligand_com_nm = tuple(float(value) for value in boundary_fields[9:12])
    handoff = compute_force_continuous_handoff(
        time_ps=time_ps,
        old_coordinate_nm=old_coordinate_nm,
        old_reference_nm=old_reference_nm,
        new_direction=(1.0, 0.0, 0.0),
        old_direction=(1.0, 0.0, 0.0),
        reference_com_nm=reference_com_nm,
        ligand_com_nm=ligand_com_nm,
        rate_nm_per_ps=0.001,
        spring_k_kj_mol_nm2=100.0,
    )
    updates = mdp_updates_for_handoff(
        handoff, init_step=100, nsteps=100, simulation_part=2
    )
    segment2_mdp = segmented / "segment2.mdp"
    segment2_mdp.write_text(
        patch_mdp_text(
            (fixture / "segment1.mdp").read_text(encoding="utf-8"), updates
        ),
        encoding="utf-8",
        newline="\n",
    )
    (segmented / "handoff.json").write_text(
        json.dumps(
            {"handoff": asdict(handoff), "mdp_updates": updates},
            indent=2,
            sort_keys=True,
            allow_nan=False,
        )
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    run(
        [
            args.gmx,
            "grompp",
            "-f",
            "segment2.mdp",
            "-c",
            "run.gro",
            "-t",
            "run.cpt",
            "-p",
            str(fixture / "topol.top"),
            "-n",
            str(fixture / "index.ndx"),
            "-o",
            "segment2.tpr",
            "-po",
            "mdout_segment2.mdp",
            "-maxwarn",
            "0",
        ],
        cwd=segmented,
        log=segmented / "grompp_segment2.txt",
    )
    run(
        [
            args.gmx,
            "mdrun",
            "-s",
            "segment2.tpr",
            "-deffnm",
            "run",
            "-px",
            "pullx.xvg",
            "-pf",
            "pullf.xvg",
            "-cpo",
            "run.cpt",
            "-cpi",
            "run.cpt",
            "-reprod",
            "-ntmpi",
            "1",
            "-ntomp",
            "1",
        ],
        cwd=segmented,
        log=segmented / "mdrun_segment2.txt",
    )

    run(
        [
            args.gmx,
            "grompp",
            "-f",
            str(fixture / "monolithic.mdp"),
            *common_grompp,
            "-o",
            "run.tpr",
            "-po",
            "mdout.mdp",
        ],
        cwd=monolithic,
        log=monolithic / "grompp.txt",
    )
    run(
        [
            args.gmx,
            "mdrun",
            "-s",
            "run.tpr",
            "-deffnm",
            "run",
            "-px",
            "pullx.xvg",
            "-pf",
            "pullf.xvg",
            "-cpo",
            "run.cpt",
            "-reprod",
            "-ntmpi",
            "1",
            "-ntomp",
            "1",
        ],
        cwd=monolithic,
        log=monolithic / "mdrun.txt",
    )

    pullx_identical = xvg_rows(segmented / "pullx.xvg") == xvg_rows(
        monolithic / "pullx.xvg"
    )
    pullf_identical = xvg_rows(segmented / "pullf.xvg") == xvg_rows(
        monolithic / "pullf.xvg"
    )
    compared_files = ("run.gro", "run.trr", "run.xtc", "run.edr")
    file_hashes = {
        name: {
            "segmented": sha256(segmented / name),
            "monolithic": sha256(monolithic / name),
        }
        for name in compared_files
    }
    binary_identical = {
        name: values["segmented"] == values["monolithic"]
        for name, values in file_hashes.items()
    }
    run(
        [
            args.gmx,
            "check",
            "-f",
            str(monolithic / "run.trr"),
            "-f2",
            str(segmented / "run.trr"),
        ],
        cwd=output,
        log=output / "gmx_check_trr.txt",
    )
    run(
        [
            args.gmx,
            "check",
            "-e",
            str(monolithic / "run.edr"),
            "-e2",
            str(segmented / "run.edr"),
        ],
        cwd=output,
        log=output / "gmx_check_edr.txt",
    )

    passed = (
        pullx_identical
        and pullf_identical
        and all(binary_identical.values())
        and handoff.extension_residual_nm == 0.0
        and handoff.energy_residual_kj_mol == 0.0
        and handoff.force_magnitude_residual_kj_mol_nm == 0.0
    )
    report = {
        "schema": "titan-path-gromacs-g1-report-v1",
        "status": "PASS" if passed else "FAIL",
        "gromacs_version_banner": gmx_version.splitlines()[:12],
        "fixture_sha256": {
            path.name: sha256(path)
            for path in sorted(fixture.iterdir())
            if path.is_file()
        },
        "boundary": {
            "time_ps": time_ps,
            "coordinate_nm": old_coordinate_nm,
            "reference_nm": old_reference_nm,
            "reference_com_nm": reference_com_nm,
            "ligand_com_nm": ligand_com_nm,
        },
        "handoff": asdict(handoff),
        "numeric_pullx_rows": len(xvg_rows(segmented / "pullx.xvg")),
        "numeric_pullf_rows": len(xvg_rows(segmented / "pullf.xvg")),
        "pullx_numeric_identical": pullx_identical,
        "pullf_numeric_identical": pullf_identical,
        "binary_identical": binary_identical,
        "file_sha256": file_hashes,
    }
    (output / "report.json").write_text(
        json.dumps(report, indent=2, sort_keys=True, allow_nan=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(json.dumps(report, indent=2, sort_keys=True, allow_nan=False))
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
