#!/usr/bin/env python3
"""Write src/vibe_only/absent_entry_points.cpp for the TITAN-VIBE build (VIBE_ONLY=1).

The VIBE-only build compiles the TITAN engine unchanged but leaves out the
energy, solvation, kinetics and analysis modules. The engine still names their
entry points, so the link reports them as undefined. This script reads those
symbols from a link log, finds each declaration with clang's AST dump, and
writes one definition per symbol:

- an entry point listed in src/vibe_only/disabled_entry_points.txt (one the
  engine calls on every run) does nothing and returns a value-initialized
  result, as the module does when its options are off;
- every other one calls titan_vibe_only::absent(), which stops the program.

usage (from the repository root):
  make VIBE_ONLY=1 ... all LDFLAGS="... -Wl,--no-demangle" > link.log 2>&1   # fails at the link
  python tools/vibe_only/generate_absent_entry_points.py --link-log link.log --append \
      --clang clang++ --cxxflags "<the -I, -D, -std and -m flags of the build>"
  make VIBE_ONLY=1 ... all                                                  # links

Run it again (with --append) whenever the link reports undefined symbols, or
after editing disabled_entry_points.txt (no clang run is needed then). The
output is ordinary C++ and compiles on every platform the build supports.
"""
from __future__ import annotations

import argparse
import json
import re
import shlex
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

HEADER = """\
// Generated by tools/vibe_only/generate_absent_entry_points.py. Do not edit.
//
// TITAN-VIBE (VIBE_ONLY=1): the entry points that the TITAN engine names in
// modules this build leaves out. Those the engine calls on every run (listed in
// disabled_entry_points.txt) do nothing, as the module does with its options
// off; every other one stops the program through titan_vibe_only::absent().
// option_allowlist.cpp refuses every option of these modules, so a VIBE run
// never reaches absent(). See src/vibe_only/absent.h.

"""
# The headers that declare the entry points: those of the engine and of the
# root files that call into the missing modules.
PROBE_INCLUDES = ["engine/engine_run.h", "energy/group_bonds.h", "gbsa/gb_topology_pairs.h", "titan_tpt.h"]
MARK = "\n// ---- entry points ----\n\n"
UNDEFINED_PATTERNS = [
    re.compile(r"undefined symbol: (\S+)"),          # ld.lld
    re.compile(r"undefined reference to [`'](\S+?)'"),  # GNU ld
]
FUNCTION_KINDS = {"FunctionDecl", "CXXMethodDecl", "CXXConstructorDecl", "CXXDestructorDecl",
                  "CXXConversionDecl"}


def undefined_symbols(log_text: str) -> list[str]:
    found = []
    for pattern in UNDEFINED_PATTERNS:
        found += pattern.findall(log_text)
    return sorted(set(found))


def demangle(symbols: list[str], cxxfilt: str) -> dict[str, str]:
    out = subprocess.run([cxxfilt], input="\n".join(symbols), capture_output=True, text=True, check=True)
    return dict(zip(symbols, out.stdout.splitlines()))


def qualified_name(demangled: str) -> str:
    """'ns::Cls::f(int) const' -> 'ns::Cls::f' (abi tags dropped)."""
    depth = 0
    for i, ch in enumerate(demangled):
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        elif ch == "(" and depth == 0 and not demangled[:i].endswith("operator"):
            return re.sub(r"\[abi:[^\]]*\]", "", demangled[:i])
    return demangled


def scope_and_name(qual: str) -> tuple[str, str]:
    depth = 0
    for i in range(len(qual) - 1, 0, -1):
        ch = qual[i]
        if ch == ">":
            depth += 1
        elif ch == "<":
            depth -= 1
        elif depth == 0 and qual[i] == ":" and qual[i - 1] == ":":
            return qual[: i - 1], qual[i + 1 :]
    return "", qual


def dump_declarations(filter_name: str, clang: str, cxxflags: list[str], probe: Path) -> list[dict]:
    cmd = [clang, *cxxflags, "-fsyntax-only", "-Xclang", "-ast-dump=json", "-Xclang",
           f"-ast-dump-filter={filter_name}", str(probe)]
    out = subprocess.run(cmd, capture_output=True, text=True, errors="replace")
    if out.returncode != 0:
        raise SystemExit(f"clang failed for filter {filter_name}:\n{out.stderr[-3000:]}")
    decoder = json.JSONDecoder()
    text, pos, nodes = out.stdout, 0, []
    while True:
        while pos < len(text) and text[pos] != "{":
            pos += 1
        if pos >= len(text):
            return nodes
        node, pos = decoder.raw_decode(text, pos)
        nodes.append(node)


def walk(node: dict):
    yield node
    for child in node.get("inner", []):
        yield from walk(child)


def split_function_type(qual_type: str) -> tuple[str, str]:
    """'R (P1, P2) const noexcept' -> ('R', 'const noexcept')."""
    depth = 0
    for i, ch in enumerate(qual_type):
        if ch in "<[":
            depth += 1
        elif ch in ">]":
            depth -= 1
        elif ch == "(" and depth == 0:
            close, nest = i, 0
            for j in range(i, len(qual_type)):
                if qual_type[j] == "(":
                    nest += 1
                elif qual_type[j] == ")":
                    nest -= 1
                    if nest == 0:
                        close = j
                        break
            tail = qual_type[close + 1 :].strip()
            if tail.startswith("("):
                raise ValueError(f"function returning a function pointer: {qual_type}")
            return qual_type[:i].strip(), tail
    raise ValueError(f"not a function type: {qual_type}")


def declaration(node: dict, scope: str, name: str) -> str:
    """The definition head at global scope, with the fully qualified name.

    The parameter types and the trailing return type of a qualified definition
    are looked up in the scope of the class or namespace that qualifies it, so
    the types print exactly as clang spells them in the declaration.
    """
    params = [p["type"]["qualType"] for p in node.get("inner", []) if p.get("kind") == "ParmVarDecl"]
    if node.get("variadic"):
        params.append("...")
    ret, tail = split_function_type(node["type"]["qualType"])
    qualified = f"{scope}::{name}" if scope else name
    tail = (" " + tail) if tail else ""
    plist = ", ".join(params)
    kind = node["kind"]
    if kind in ("CXXConstructorDecl", "CXXDestructorDecl"):
        return f"{qualified}({plist}){tail}"
    if kind == "CXXConversionDecl":
        return f"{qualified}(){tail}"
    return f"auto {qualified}({plist}){tail} -> {ret}"


def body(head: str, name: str, disabled: bool) -> str:
    if not disabled:
        return f'{{ titan_vibe_only::absent("{name}"); }}'
    returns_value = head.startswith("auto ") and not head.endswith("-> void") or "::operator " in head
    return "{ return {}; }" if returns_value else "{}"


def read_disabled(path: Path) -> set[str]:
    names = set()
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.add(line)
    return names


def read_entries(path: Path) -> dict[str, str]:
    """readable name -> definition head, from an earlier output."""
    entries = {}
    old = path.read_text().split(MARK, 1)[-1]
    for block in old.strip().split("\n\n"):
        lines = block.split("\n")
        if len(lines) >= 2 and lines[0].startswith("// "):
            entries[lines[0][3:]] = re.sub(r" \{.*\}\s*$", "", lines[1])
    return entries


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--link-log", required=True, type=Path)
    ap.add_argument("--clang", default="clang++")
    ap.add_argument("--cxxfilt", default="c++filt")
    ap.add_argument("--cxxflags", default="", help="include and define flags of the build, one string")
    ap.add_argument("--output", type=Path, default=Path("src/vibe_only/absent_entry_points.cpp"))
    ap.add_argument("--disabled", type=Path, default=Path("src/vibe_only/disabled_entry_points.txt"))
    ap.add_argument("--append", action="store_true", help="keep the entry points already in --output")
    ap.add_argument("--remove", action="append", default=[], metavar="NAME",
                    help="with --append: drop the entry point NAME (as absent() names it), e.g. after "
                         "defining it in disabled_modules.cpp; repeatable")
    args = ap.parse_args()

    entries = read_entries(args.output) if args.append and args.output.exists() else {}
    for name in args.remove:
        dropped = [k for k in entries if qualified_name(k) == name]
        if not dropped:
            raise SystemExit(f"--remove {name}: no such entry point in {args.output}")
        for k in dropped:
            del entries[k]

    symbols = undefined_symbols(args.link_log.read_text(errors="replace"))
    not_cxx = [s for s in symbols if not s.startswith("_Z")]
    if not_cxx:
        raise SystemExit(f"undefined symbols that are not C++ functions: {not_cxx}")
    readable = demangle(symbols, args.cxxfilt) if symbols else {}
    symbols = [s for s in symbols if readable[s] not in entries]

    found: dict[str, tuple[dict, str, str]] = {}
    if symbols:
        by_scope: dict[str, list[str]] = defaultdict(list)
        for s in symbols:
            scope, _ = scope_and_name(qualified_name(readable[s]))
            by_scope[scope or qualified_name(readable[s])].append(s)
        cxxflags = shlex.split(args.cxxflags)
        with tempfile.TemporaryDirectory() as tmp:
            probe = Path(tmp) / "probe.cpp"
            probe.write_text("".join(f'#include "{h}"\n' for h in PROBE_INCLUDES))
            for i, (scope, syms) in enumerate(sorted(by_scope.items()), 1):
                wanted = set(syms)
                filter_name = scope + "::" if any(qualified_name(readable[s]) != scope for s in syms) else scope
                print(f"[{i}/{len(by_scope)}] {filter_name} ({len(syms)})", flush=True)
                for top in dump_declarations(filter_name, args.clang, cxxflags, probe):
                    for node in walk(top):
                        m = node.get("mangledName")
                        if node.get("kind") in FUNCTION_KINDS and m in wanted and m not in found:
                            s, n = scope_and_name(qualified_name(readable[m]))
                            found[m] = (node, s, n)
        for m, (node, scope, name) in found.items():
            entries[readable[m]] = declaration(node, scope, name)

    disabled = read_disabled(args.disabled) if args.disabled.exists() else set()
    known = {qualified_name(k) for k in entries}
    unknown = sorted(disabled - known)
    if unknown:
        raise SystemExit(f"{args.disabled} names entry points that are not in the table: {unknown}")

    lines = [HEADER, '#include "vibe_only/absent.h"\n']
    lines += [f'#include "{h}"\n' for h in PROBE_INCLUDES]
    lines.append(MARK)
    blocks = []
    for k in sorted(entries):
        name = qualified_name(k)
        head = entries[k]
        blocks.append(f"// {k}\n{head} {body(head, name, name in disabled)}")
    lines.append("\n\n".join(blocks) + "\n")
    args.output.write_text("".join(lines))
    n_disabled = sum(qualified_name(k) in disabled for k in entries)
    print(f"wrote {args.output}: {len(entries)} entry points, {n_disabled} disabled, "
          f"{len(found)} new")
    missing = [readable[s] for s in symbols if s not in found]
    if missing:
        print("no declaration found (add the declaring header to PROBE_INCLUDES and rerun with --append):\n  "
              + "\n  ".join(missing))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
