#!/usr/bin/env python3
"""Copy the files of the TITAN-VIBE build (VIBE_ONLY=1) into a new source tree.

The list comes from the dependency files (.d) the compiler wrote for the
VIBE-only build, so it holds exactly the sources and headers that build reads,
plus the Makefile and the generators the Makefile runs. License notices of the
directories that contribute files are copied too.

usage (from the repository root, after a VIBE-only build):
  python tools/vibe_only/export_source.py --build-dir build/vibe-portable --output <new dir>
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

ALWAYS = [
    "Makefile",
    "VERSION",
    "LICENSE",
    "tools/generate_build_info.py",
    "tools/generate_cli_registry.py",
    "tools/vibe_only/generate_absent_entry_points.py",
    "tools/vibe_only/export_source.py",
    "src/vibe_only/README.md",
    "src/vibe_only/disabled_entry_points.txt",
]
NOTICE_NAMES = ("COPYING", "LICENSE", "NOTICE")


def dependency_paths(dep_file: Path) -> list[str]:
    text = dep_file.read_text(errors="replace").replace("\\\n", " ")
    paths = []
    for line in text.splitlines():
        if ":" not in line:
            continue
        target, _, rest = line.partition(": ")
        if not rest and line.endswith(":"):
            continue  # phony header targets written by -MP
        paths += rest.split()
    return paths


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--build-dir", required=True, type=Path)
    ap.add_argument("--output", required=True, type=Path)
    ap.add_argument("--repo", type=Path, default=Path("."))
    args = ap.parse_args()

    repo = args.repo.resolve()
    build = (repo / args.build_dir).resolve()
    if args.output.exists():
        raise SystemExit(f"{args.output} exists; give a new directory")
    deps = sorted(build.rglob("*.d"))
    if not deps:
        raise SystemExit(f"no .d files under {build}; build VIBE_ONLY=1 first")

    files: set[str] = set(ALWAYS)
    for d in deps:
        for p in dependency_paths(d):
            path = (repo / p).resolve() if not Path(p).is_absolute() else Path(p).resolve()
            try:
                rel = path.relative_to(repo).as_posix()
            except ValueError:
                continue  # system and compiler headers
            if rel.startswith(build.relative_to(repo).as_posix() + "/"):
                continue  # generated by the Makefile
            files.add(rel)
    # License notices of every directory that contributes a file, and of its parents
    # (src/eigen/COPYING.* covers src/eigen/Eigen/...).
    dirs = set()
    for f in files:
        dirs.update(Path(f).parents)
    for d in sorted(dirs):
        here = repo / d
        if d == Path(".") or not here.is_dir():
            continue
        for notice in here.iterdir():
            if notice.is_file() and (notice.name.upper().startswith(NOTICE_NAMES) or notice.suffix == ".license"):
                files.add(notice.relative_to(repo).as_posix())

    missing = [f for f in sorted(files) if not (repo / f).is_file()]
    if missing:
        raise SystemExit("listed but missing: " + ", ".join(missing))
    for f in sorted(files):
        target = args.output / f
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(repo / f, target)
    cpp = sum(1 for f in files if f.endswith(".cpp"))
    print(f"copied {len(files)} files ({cpp} .cpp) into {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
